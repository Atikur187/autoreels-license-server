/**
 * AutoReels Scroll — Secure Customer License Claim API
 * Route: GET /api/license/claim?token=claim_...
 * 
 * Securely fulfills the purchased license to the customer after payment.
 * Requirements:
 * - Only reveals license if verified by authoritative webhook.
 * - Single-use / short-lived claim token correlation.
 * - Never reveals license in public checkout URLs or exposes other customer keys.
 */

import { getDb } from '../../../../lib/supabase.js';
import { PLANS } from '../../../../lib/lemonsqueezy.js';
import { handleOptions, jsonResponse } from '../../../../lib/cors.js';

export async function OPTIONS(request) {
  return handleOptions(request);
}

export async function GET(request) {
  try {
    const { searchParams } = new URL(request.url);
    const token = (searchParams.get('token') || searchParams.get('claim_token') || '').trim();

    if (!token || token.length < 10) {
      return jsonResponse(
        { success: false, ready: false, error: 'Valid claim token is required.' },
        400,
        request
      );
    }

    const db = getDb();

    // 1. Check pending_checkouts table
    let pendingRecord = null;
    try {
      const { data: checkouts } = await db
        .from('pending_checkouts')
        .select('*')
        .eq('claim_token', token);

      if (checkouts && checkouts.length > 0) {
        pendingRecord = checkouts[0];
      }
    } catch (err) {
      console.warn('[Claim API] pending_checkouts query notice:', err.message);
    }

    // Check expiration of claim token (24 hours)
    if (pendingRecord && pendingRecord.expires_at && new Date(pendingRecord.expires_at) < new Date()) {
      return jsonResponse(
        { success: false, ready: false, error: 'This claim link has expired. Please check your email or contact support.' },
        410,
        request
      );
    }

    let licenseId = pendingRecord?.license_id || null;

    // 2. If license_id not yet linked in pending_checkouts, check purchases table
    if (!licenseId) {
      const { data: purchases } = await db.from('purchases').select('*');
      const matchedPurchase = (purchases || []).find(
        (p) => p.metadata?.claim_token === token || p.metadata?.claimToken === token
      );

      if (matchedPurchase && matchedPurchase.license_id) {
        licenseId = matchedPurchase.license_id;
      }
    }

    // 3. If still no license linked, webhook has not completed yet
    if (!licenseId) {
      return jsonResponse(
        {
          success: true,
          ready: false,
          status: 'pending',
          message: 'Payment received! Your license is currently being generated by our payment processor...'
        },
        200,
        request
      );
    }

    // 4. Retrieve authoritative license record
    const { data: licenses, error: licErr } = await db
      .from('licenses')
      .select('*')
      .eq('id', licenseId);

    if (licErr || !licenses || licenses.length === 0) {
      return jsonResponse(
        { success: false, ready: false, error: 'License record not found.' },
        404,
        request
      );
    }

    const license = licenses[0];
    const planConfig = PLANS[license.plan] || { title: license.plan };

    // Mark pending checkout as claimed
    if (pendingRecord && pendingRecord.status !== 'claimed') {
      try {
        await db
          .from('pending_checkouts')
          .update({ status: 'claimed', updated_at: new Date().toISOString() })
          .eq('id', pendingRecord.id);
      } catch {}
    }

    return jsonResponse(
      {
        success: true,
        ready: true,
        licenseKey: license.license_key,
        plan: license.plan,
        planName: planConfig.title || license.plan,
        license: {
          license_key: license.license_key,
          plan: license.plan,
          planName: planConfig.title || license.plan,
          status: license.status,
          expires_at: license.expires_at,
          max_devices: license.max_devices || 1
        }
      },
      200,
      request
    );
  } catch (err) {
    console.error('[Claim API] Exception:', err);
    return jsonResponse({ success: false, error: 'Internal server error.' }, 500, request);
  }
}
